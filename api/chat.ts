export default async function handler(req: VercelRequest, res: VercelResponse) {
  // 브라우저에서 이 엔드포인트로 POST 요청만 받습니다.
  if (req.method !== "POST") {
    res.status(405).json({ error: "Method not allowed" });
    return;
  }

  if (!process.env.GEMINI_API_KEY) {
    res.status(500).json({ error: "서버에 GEMINI_API_KEY가 설정되어 있지 않습니다." });
    return;
  }

  try {
    const {
      message,
      history,
      userRole,
      filePart,
    }: {
      message: string;
      history: { role: string; parts: { text: string }[] }[];
      userRole: Role;
      filePart?: FilePart;
    } = req.body;

    const model = "gemini-flash-latest";
    const MAX_RETRIES = 3;
    const RETRY_DELAY_MS = 5000;

    const roleContext =
      userRole === "developer"
        ? "현재 학생은 '개발자(Developer)'이고 당신은 '점검자(Inspector)'입니다. 학생이 코드를 짤 수 있게 가이드하세요."
        : "현재 학생은 '점검자(Inspector)'이고 당신은 '개발자(Developer)'입니다. 당신이 논리를 제안하고 학생의 검토를 받으세요.";

    const filePromptNote = filePart
      ? "\n\n(학생이 엔트리 작업 화면 캡쳐 이미지 또는 PDF를 함께 첨부했습니다. 반드시 첨부된 내용을 먼저 확인하고 그 내용을 바탕으로 답하세요.)"
      : "";

    const fullPrompt = `${roleContext}\n\n학생의 메시지: ${message || "(첨부한 화면을 봐줘!)"}${filePromptNote}`;

    const currentTurnParts: any[] = [{ text: fullPrompt }];
    if (filePart) {
      currentTurnParts.push({
        inlineData: {
          mimeType: filePart.mimeType,
          data: filePart.data,
        },
      });
    }

    for (let attempt = 1; attempt <= MAX_RETRIES; attempt++) {
      try {
        const response = await ai.models.generateContent({
          model,
          contents: [...(history || []), { role: "user", parts: currentTurnParts }],
          config: {
            systemInstruction: SYSTEM_INSTRUCTION,
            temperature: 1.0,
          },
        });
        res.status(200).json({ text: response.text });
        return;
      } catch (error: any) {
        const isRateLimit =
          error?.status === 429 ||
          error?.message?.includes("429") ||
          error?.message?.includes("quota") ||
          error?.message?.includes("rate");

        if (isRateLimit && attempt < MAX_RETRIES) {
          await new Promise((resolve) => setTimeout(resolve, RETRY_DELAY_MS * attempt));
          continue;
        }
        throw error;
      }
    }
  } catch (error: any) {
    console.error("Gemini API error:", error);
    res.status(500).json({ error: error?.message || "서버 오류가 발생했습니다." });
  }
}
